#define CELL_W 6
#define CELL_H 10

typedef struct
{
   uint32_t *out;
   unsigned w, h;
   unsigned scale;
} canvas;

static void shade(const canvas *c, int x0, int y0, int x1, int y1, uint32_t rgb, unsigned keep)
{
   if (x0 < 0) x0 = 0;
   if (y0 < 0) y0 = 0;
   if (x1 > (int)c->w) x1 = (int)c->w;
   if (y1 > (int)c->h) y1 = (int)c->h;
   for (int y = y0; y < y1; y++)
   {
      uint32_t *row = c->out + (size_t)y * c->w;
      for (int x = x0; x < x1; x++)
      {
         uint32_t p = row[x];
         unsigned r = ((((p >> 16) & 0xFF) * keep) >> 8) + ((((rgb >> 16) & 0xFF) * (256 - keep)) >> 8);
         unsigned g = ((((p >> 8) & 0xFF) * keep) >> 8) + ((((rgb >> 8) & 0xFF) * (256 - keep)) >> 8);
         unsigned b = (((p & 0xFF) * keep) >> 8) + (((rgb & 0xFF) * (256 - keep)) >> 8);
         row[x] = (r << 16) | (g << 8) | b;
      }
   }
}

/* Draws at most `max` characters; returns how many cells that took. */
static unsigned text(const canvas *c, int x, int y, const char *s, unsigned max, uint32_t rgb)
{
   unsigned n = 0;
   for (; s && *s && n < max; s++, n++)
   {
      unsigned ch = (unsigned char)*s;
      const uint8_t *glyph = font[ch >= 32 && ch < 127 ? ch - 32 : '?' - 32];
      for (unsigned col = 0; col < 5; col++)
         for (unsigned row = 0; row < 8; row++)
         {
            int px, py;
            if (!((glyph[col] >> row) & 1))
               continue;
            px = x + (int)((n * CELL_W + col) * c->scale);
            py = y + (int)(row * c->scale);
            for (unsigned v = 0; v < c->scale; v++)
               for (unsigned u = 0; u < c->scale; u++)
               {
                  int X = px + (int)u, Y = py + (int)v;
                  if (X >= 0 && Y >= 0 && X < (int)c->w && Y < (int)c->h)
                     c->out[(size_t)Y * c->w + (size_t)X] = rgb;
               }
         }
   }
   return n;
}

void px_panel_draw(uint32_t *out, unsigned w, unsigned h, const px_panel *p)
{
   canvas c;
   unsigned cols, cw, ch;

   if (!out || !p || !w || !h)
      return;
   c.out   = out;
   c.w     = w;
   c.h     = h;
   c.scale = w >= 1800 ? 4 : w >= 1200 ? 3 : w >= 600 ? 2 : 1;
   cw      = CELL_W * c.scale;
   ch      = CELL_H * c.scale;
   cols    = w / cw;
   if (cols > 52)
      cols = 52;
   if (cols < 8)
      return;

   if (!p->open)
   {
      unsigned n;
      int x, y;
      if (!p->toast || !*p->toast)
         return;
      n = (unsigned)strlen(p->toast);
      if (n > cols - 2)
         n = cols - 2;
      x = (int)(w - (n + 2) * cw) / 2;
      y = (int)(h - 3 * ch);
      shade(&c, x, y, x + (int)((n + 2) * cw), y + (int)(ch * 2), 0x000818, 70);
      text(&c, x + (int)cw, y + (int)(ch / 2) + (int)c.scale, p->toast, n, 0xFFFFFF);
      return;
   }

   {
      /* As many lines as fit, around the selected one. */
      unsigned room = h / ch, lines, first = 0;
      unsigned name_cols = cols >= 52 ? 27 : (cols - 4) * 3 / 5, value_cols = cols - 4 - name_cols;
      int x, y, box_w, box_h;

      if (room < 6)
         return;
      lines = p->count < room - 5 ? p->count : room - 5;
      if (p->selected >= lines)
         first = p->selected - lines + 1;
      box_w = (int)(cols * cw);
      box_h = (int)((lines + 4) * ch);
      x     = (int)(w - (unsigned)box_w) / 2;
      y     = (int)(h - (unsigned)box_h) / 2;

      shade(&c, x, y, x + box_w, y + box_h, 0x000818, 50);
      shade(&c, x, y, x + box_w, y + (int)(ch * 3 / 2), 0x204080, 60);
      text(&c, x + (int)(2 * cw), y + (int)(ch / 4) + (int)c.scale, p->title ? p->title : "Proteus",
            cols - 4, 0xFFFFFF);

      for (unsigned i = 0; i < lines; i++)
      {
         unsigned k = first + i;
         int ly = y + (int)((i + 2) * ch);
         bool on = k == p->selected;
         if (on)
            shade(&c, x + (int)cw, ly - (int)c.scale, x + box_w - (int)cw,
                  ly + (int)(ch - c.scale), 0xFFD040, 40);
         text(&c, x + (int)(2 * cw), ly, p->names[k], name_cols - 1, on ? 0x000000 : 0xC0D0E0);
         text(&c, x + (int)((2 + name_cols) * cw), ly, p->values[k], value_cols,
               on ? 0x000000 : 0xFFFFFF);
      }
      if (p->hint)
         text(&c, x + (int)(2 * cw), y + (int)((lines + 2) * ch) + (int)(ch / 2), p->hint,
               cols - 4, 0x80A0C0);
   }
}
